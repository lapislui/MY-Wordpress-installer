  saveInstallerDbProfile: (profile) => ipcRenderer.invoke("vault:save-installer-db", profile),
  clearInstallerDbProfile: () => ipcRenderer.invoke("vault:clear-installer-db"),
  getSiteCredentials: (key) => ipcRenderer.invoke("vault:get-site-credentials", key),
