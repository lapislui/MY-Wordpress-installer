  saveBackup: (siteName) => ipcRenderer.invoke("dialog:save-backup", siteName),
  browserCreateTab: (payload) => ipcRenderer.invoke("browser:create-tab", payload),
  browserActivateTab: (tabId) => ipcRenderer.invoke("browser:activate-tab", tabId),
  browserCloseTab: (tabId) => ipcRenderer.invoke("browser:close-tab", tabId),
  browserNavigate: (url) => ipcRenderer.invoke("browser:navigate", url),
  browserGetSuggestions: (query) => ipcRenderer.invoke("browser:get-suggestions", query),
  browserGoBack: () => ipcRenderer.invoke("browser:go-back"),
  browserGoForward: () => ipcRenderer.invoke("browser:go-forward"),
  browserReload: () => ipcRenderer.invoke("browser:reload"),
  browserAutofillCredentials: (payload) => ipcRenderer.invoke("browser:autofill-credentials", payload),
  browserShowAppMenu: (payload) => ipcRenderer.invoke("browser:show-app-menu", payload),
  browserFindInPage: (text) => ipcRenderer.invoke("browser:find-in-page", text),
  browserUpdateLayout: (payload) => ipcRenderer.invoke("browser:update-layout", payload),
  browserPickDownloadDirectory: () => ipcRenderer.invoke("browser:pick-download-directory"),
  browserOpenDownload: (downloadId) => ipcRenderer.invoke("browser:open-download", downloadId),
  browserShowDownload: (downloadId) => ipcRenderer.invoke("browser:show-download", downloadId),
  browserClearDownloads: () => ipcRenderer.invoke("browser:clear-downloads"),
  browserClearPermission: (payload) => ipcRenderer.invoke("browser:clear-permission", payload),
  browserAddBookmark: (payload) => ipcRenderer.invoke("browser:add-bookmark", payload),
