  backupSite: (payload) => ipcRenderer.invoke("sites:backup", payload),
  deleteSite: (payload) => ipcRenderer.invoke("sites:delete", payload),
  showSiteContextMenu: (site) => ipcRenderer.invoke("sites:show-context-menu", site),
