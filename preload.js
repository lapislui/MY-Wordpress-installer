  browserCreateWindow: (payload) => ipcRenderer.invoke("browser:create-window", payload),
  browserShowBookmarkContextMenu: (payload) => ipcRenderer.invoke("browser:show-bookmark-context-menu", payload),
  browserShowTabContextMenu: (tabId) => ipcRenderer.invoke("browser:show-tab-context-menu", tabId),
